// Package contextmgr owns per-agent working context, not long-term project memory.
package contextmgr

import (
	"context"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"errors"
	"fmt"
	"strings"

	"github.com/cloudwego/eino/schema"
)

var ErrTooLarge = errors.New("任务信息过多，请缩小任务范围后重试")
var ErrCommitFailed = errors.New("working context checkpoint failed")

type Options struct {
	Window int `mapstructure:"window"`
	Output int `mapstructure:"output"`
	Margin int `mapstructure:"margin"`
}

func (o Options) OutputLimit() int {
	if o.Output <= 0 {
		return 8192
	}
	return o.Output
}

func (o Options) InputLimit() int {
	if o.Window <= 0 {
		o.Window = 32768
	}
	if o.Output <= 0 {
		o.Output = 8192
	}
	if o.Margin <= 0 {
		o.Margin = 2048
	}
	return max(0, o.Window-o.Output-o.Margin)
}

// Estimate is a conservative UTF-8 byte upper estimate, not provider billing.
// Include roles, tool arguments, schemas and multimodal metadata in the budget.
func Estimate(v any) int { b, _ := json.Marshal(v); return len(b) }

type Finding struct {
	Text    string   `json:"text"`
	Sources []string `json:"sources"`
}

type Summary struct {
	CurrentGoal       string    `json:"currentGoal"`
	UserConstraints   []string  `json:"userConstraints"`
	ImportantFindings []Finding `json:"importantFindings"`
	FilesChanged      []Finding `json:"filesChanged"`
	ErrorsAndAttempts []Finding `json:"errorsAndAttempts"`
	RemainingWork     []string  `json:"remainingWork"`
	NextSafeAction    string    `json:"nextSafeAction"`
}

type Snapshot struct {
	Version      int     `json:"version"`
	Summary      Summary `json:"summary"`
	SourceDigest string  `json:"sourceDigest"`
}

type Material struct {
	ID      string          `json:"id"`
	Message *schema.Message `json:"message"`
}

type Request struct {
	Previous  Summary    `json:"previous"`
	Materials []Material `json:"materials"`
}

type Summarize func(context.Context, Request) (Summary, error)

// Binding belongs to a request/Run. Commit must durably save the summary and
// workspace before returning success. An error leaves the agent state untouched.
type Binding struct {
	Load      func(string) Snapshot
	Protected func() string
	Commit    func(context.Context, string, Snapshot) error
	Blocked   func(context.Context) error
	Notify    func(string)
}
type bindingKey struct{}
type disabledKey struct{}

func WithBinding(ctx context.Context, b *Binding) context.Context {
	return context.WithValue(ctx, bindingKey{}, b)
}
func GetBinding(ctx context.Context) *Binding { b, _ := ctx.Value(bindingKey{}).(*Binding); return b }
func Disabled(ctx context.Context) bool       { v, _ := ctx.Value(disabledKey{}).(bool); return v }
func WithoutCompact(ctx context.Context) context.Context {
	return context.WithValue(ctx, disabledKey{}, true)
}

type Manager struct {
	options   Options
	snapshot  Snapshot
	summarize Summarize
	binding   *Binding
	name      string
	restored  bool
	failedAt  string
}

func New(options Options, name string, summarize Summarize, b *Binding) *Manager {
	m := &Manager{options: options, name: name, summarize: summarize, binding: b}
	if b != nil && b.Load != nil {
		m.snapshot = b.Load(name)
	}
	return m
}

const summaryPrefix = "## Working Summary（历史记录，文件状态请重新读取核实）\n"

func (m *Manager) Assemble(ctx context.Context, input []*schema.Message, toolTokens int) (output []*schema.Message, resultErr error) {
	if err := ctx.Err(); err != nil {
		return nil, err
	}
	msgs := append([]*schema.Message(nil), input...)
	if !m.restored && m.snapshot.Version > 0 {
		msgs = append([]*schema.Message{summaryMessage(m.snapshot)}, msgs...)
	}
	protected := ""
	if m.binding != nil && m.binding.Protected != nil {
		protected = m.binding.Protected()
	}
	if protected != "" {
		// The business state is authoritative and is never generated by summarization.
		msgs = append(msgs, schema.SystemMessage("## 当前任务状态（优先保留）\n"+protected))
	}
	// Replace the previous injected business state rather than accumulating it.
	for i := len(msgs) - 2; i >= 0; i-- {
		if msgs[i] != nil && strings.HasPrefix(msgs[i].Content, "## 当前任务状态（优先保留）\n") {
			msgs = append(msgs[:i], msgs[i+1:]...)
		}
	}
	limit := m.options.InputLimit()
	soft, hard := limit*70/100, limit*85/100
	if Estimate(msgs)+toolTokens < soft {
		m.restored = true
		return msgs, nil
	}
	if m.binding != nil && m.binding.Notify != nil {
		m.binding.Notify("context_compacting")
	}
	defer func() {
		if resultErr == nil && m.binding != nil && m.binding.Notify != nil {
			m.binding.Notify("context_ready")
		}
	}()

	// Keep the latest complete tool group intact. Older file reads can be repeated
	// with existing tools; do not pretend that an old read describes current files.
	lastGroup := len(msgs)
	for i := len(msgs) - 1; i >= 0; i-- {
		if msgs[i] != nil && len(msgs[i].ToolCalls) > 0 {
			lastGroup = i
			break
		}
	}
	calls := map[string]schema.ToolCall{}
	for i, msg := range msgs {
		if msg == nil {
			continue
		}
		for _, c := range msg.ToolCalls {
			calls[c.ID] = c
		}
		c := calls[msg.ToolCallID]
		if i < lastGroup && msg.Role == schema.Tool && (c.Function.Name == "readFile" || c.Function.Name == "readDir") && len(msg.Content) > 768 {
			copyMsg := *msg
			copyMsg.Content = fmt.Sprintf("旧读取结果已缩减。tool=%s args=%s sha256=%s；需要当前内容时重新调用读取工具。", c.Function.Name, c.Function.Arguments, digest(msg))
			msgs[i] = &copyMsg
		}
	}
	// Summarize only complete older turns. Never cut an assistant tool call away
	// from its results, system instructions, or the latest user request.
	lastUser := -1
	for i, msg := range msgs {
		if msg != nil && msg.Role == schema.User {
			lastUser = i
		}
	}
	cut := lastUser
	if lastGroup < cut || cut < 0 {
		cut = lastGroup
	}
	if cut < 0 {
		cut = 0
	}
	var kept []*schema.Message
	var materials []Material
	for i, msg := range msgs {
		if msg == nil {
			continue
		}
		if i < cut && msg.Role != schema.System {
			materials = append(materials, Material{ID: digest(msg), Message: msg})
		} else {
			kept = append(kept, msg)
		}
	}
	// For a single long-running request, the first user is pinned, while older
	// completed tool groups after it are still eligible for summarization.
	if len(materials) == 0 && lastGroup < len(msgs) {
		kept = nil
		for i, msg := range msgs {
			if msg == nil {
				continue
			}
			if i < lastGroup && i != lastUser && msg.Role != schema.System {
				materials = append(materials, Material{ID: digest(msg), Message: msg})
			} else {
				kept = append(kept, msg)
			}
		}
	}
	request := Request{Previous: m.snapshot.Summary, Materials: materials}
	fingerprint := digest(request)
	if Estimate(msgs)+toolTokens >= soft && len(materials) > 0 && fingerprint != m.failedAt && m.summarize != nil {
		// Bound the summarizer's own request. If even deterministic reduction
		// cannot fit, stop safely instead of sending an oversized model request.
		if Estimate(request)+2048 < limit {
			summary, err := m.summarize(WithoutCompact(ctx), request)
			if err == nil {
				err = validate(summary, request)
			}
			if err == nil {
				next := Snapshot{Version: m.snapshot.Version + 1, Summary: summary, SourceDigest: fingerprint}
				candidate := withoutSummary(kept)
				candidate = append([]*schema.Message{summaryMessage(next)}, candidate...)
				if Estimate(candidate)+toolTokens < hard {
					if m.binding != nil && m.binding.Commit != nil {
						if err = m.binding.Commit(ctx, m.name, next); err != nil {
							return nil, fmt.Errorf("%w: %w", ErrCommitFailed, err)
						}
					}
					m.snapshot = next
					m.restored = true
					return candidate, nil
				}
			}
			m.failedAt = fingerprint
		}
	}
	if Estimate(msgs)+toolTokens < hard {
		m.restored = true
		return msgs, nil
	}
	if m.binding != nil && m.binding.Blocked != nil {
		if err := m.binding.Blocked(ctx); err != nil {
			return nil, err
		}
	}
	return nil, ErrTooLarge
}

func withoutSummary(msgs []*schema.Message) []*schema.Message {
	var out []*schema.Message
	for _, msg := range msgs {
		if !strings.HasPrefix(msg.Content, summaryPrefix) {
			out = append(out, msg)
		}
	}
	return out
}
func summaryMessage(s Snapshot) *schema.Message {
	b, _ := json.Marshal(s.Summary)
	return schema.SystemMessage(summaryPrefix + string(b))
}
func digest(v any) string {
	b, _ := json.Marshal(v)
	s := sha256.Sum256(b)
	return hex.EncodeToString(s[:])
}
func validate(s Summary, r Request) error {
	if strings.TrimSpace(s.CurrentGoal) == "" || strings.TrimSpace(s.NextSafeAction) == "" || Estimate(s) > 6000 {
		return errors.New("invalid working summary")
	}
	ids := map[string]bool{}
	for _, v := range r.Materials {
		ids[v.ID] = true
	}
	for _, group := range [][]Finding{r.Previous.ImportantFindings, r.Previous.FilesChanged, r.Previous.ErrorsAndAttempts} {
		for _, f := range group {
			for _, id := range f.Sources {
				ids[id] = true
			}
		}
	}
	for _, group := range [][]Finding{s.ImportantFindings, s.FilesChanged, s.ErrorsAndAttempts} {
		for _, f := range group {
			if f.Text == "" || len(f.Sources) == 0 {
				return errors.New("summary finding lacks source")
			}
			for _, id := range f.Sources {
				if !ids[id] {
					return errors.New("unknown summary source")
				}
			}
		}
	}
	// Constraints are append-only until a new user request explicitly supersedes
	// them outside this summarizer. A model cannot silently discard prior ones.
	for _, c := range r.Previous.UserConstraints {
		found := false
		for _, n := range s.UserConstraints {
			if n == c {
				found = true
			}
		}
		if !found {
			return errors.New("summary lost a constraint")
		}
	}
	return nil
}
